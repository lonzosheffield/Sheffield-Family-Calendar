//! PWA plumbing for the phone surface (PLAN v2 **D6**, task **T2.2**).
//!
//! Three things live here, and they are deliberately together because they
//! are one contract:
//!
//! 1. [`MANIFEST_JSON`] — the web app manifest, served from **root** at
//!    `/manifest.webmanifest` with `scope: "/"` and `start_url: "/m"`. G6/R-16
//!    was that the v1 manifest went out from a hashed `asset!()` path under
//!    `/assets/`, which puts `start_url` *outside* the manifest's own scope
//!    and makes the install prompt impossible however many icons it lists.
//!    Nothing in this file may ever acquire a content hash for that reason.
//! 2. [`SERVICE_WORKER_JS`] — `sw.js`, `include_str!`'d from the file next to
//!    this one (`docs/NON_RUST.md` declares it) and served from root so its
//!    default scope is `/`.
//! 3. [`ICONS`] — the T0.7 icon set, `include_bytes!`'d into the binary and
//!    served from stable `/icons/<name>.png` URLs. Embedding them rather than
//!    pointing the manifest at `asset!()` output keeps the manifest hash-free
//!    (see 1) *and* means an install can never fail because a `dx build` step
//!    did not copy a file.
//!
//! Registration itself is [`register_service_worker`], called once by
//! [`super::MobileShell`] via `web_sys`.

/// The web app manifest, byte for byte.
///
/// Hand-written Rust rather than an included `.json` so the whole PWA
/// surface stays inside the Rust stack (only `sw.js` is a declared non-Rust

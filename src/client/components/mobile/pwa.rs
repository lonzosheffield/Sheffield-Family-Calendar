/// The manifest's canonical, hash-free URL (PLAN v2 D6 / R-16).
pub const MANIFEST_PATH: &str = "/manifest.webmanifest";
/// The service worker's canonical, hash-free URL. Root-served so its default
/// registration scope is `/`, which is what `scope: "/"` in the manifest
/// requires.
pub const SERVICE_WORKER_PATH: &str = "/sw.js";
/// `Content-Type` browsers require before they will treat the manifest as one.
pub const MANIFEST_CONTENT_TYPE: &str = "application/manifest+json";
/// `Content-Type` for `sw.js`. A service worker served as anything but a
/// JavaScript MIME type is rejected outright by every browser.
pub const SERVICE_WORKER_CONTENT_TYPE: &str = "text/javascript";

/// `sw.js`, compiled into the binary (`docs/NON_RUST.md`, PLAN v2 D6:
/// "`sw.js` ≈ 40 lines from `include_str!`").
pub const SERVICE_WORKER_JS: &str = include_str!("sw.js");

/// The PWA icon set generated by T0.7's `xtask`, embedded so the install
/// prompt can never be blocked by a missing file.
pub const ICONS: [(&str, &[u8]); 4] = [
    (
        "icon-192.png",
        include_bytes!("../../../../assets/icons/icon-192.png"),
    ),
    (
        "icon-512.png",
        include_bytes!("../../../../assets/icons/icon-512.png"),
    ),
    (
        "icon-192-maskable.png",
        include_bytes!("../../../../assets/icons/icon-192-maskable.png"),
    ),
    (
        "icon-512-maskable.png",
        include_bytes!("../../../../assets/icons/icon-512-maskable.png"),
    ),
];

/// The bytes of the embedded icon called `name`, or `None`.
///
/// Deliberately an exact-name lookup against a fixed table rather than a
/// filesystem read: `/icons/<file>` is a user-supplied path segment, and a
/// table lookup cannot be walked out of with `..`.
pub fn icon_bytes(name: &str) -> Option<&'static [u8]> {
    ICONS
        .iter()
        .find(|(icon_name, _)| *icon_name == name)
        .map(|(_, bytes)| *bytes)
}

/// Is `url` inside `scope`? (R-16.)
///
/// The manifest algorithm is a path-prefix match on the same origin, with the
/// scope treated as ending at a path segment boundary — so `/m` is inside
/// `/`, and inside `/m`, but `/mobile` is **not** inside `/m/`. This is the
/// exact rule that made the v1 manifest uninstallable: served from a hashed
/// `/assets/…` URL, its implicit scope was `/assets/`, which does not contain
/// `start_url: "/m"`, so the browser rejected the manifest outright.
pub fn path_is_within_scope(scope: &str, url: &str) -> bool {
    if scope == "/" {
        return url.starts_with('/');
    }
    let scope = scope.strip_suffix('/').unwrap_or(scope);
    url == scope || url.starts_with(&format!("{scope}/"))
}

/// Does `path` look like it carries a build-time content hash?
///
/// A cheap, deliberate heuristic: any run of eight or more hexadecimal
/// characters. `dx`'s `asset!()` output (`…-dx<16 hex>.json`) trips it;
/// `/manifest.webmanifest`, `/sw.js` and `/icons/icon-192.png` do not. It
/// exists so `tests/pwa_tests.rs` can fail loudly if anyone ever routes the
/// manifest or the service worker back through the asset pipeline and
/// silently re-breaks installability (G6).
pub fn contains_content_hash(path: &str) -> bool {
    let mut run = 0usize;
    for ch in path.chars() {
        if ch.is_ascii_hexdigit() {
            run += 1;
            if run >= 8 {
                return true;
            }
        } else {
            run = 0;
        }
    }
    false
}

// ---------------------------------------------------------------------------
// Registration (browser side)
// ---------------------------------------------------------------------------

/// Register `/sw.js` with the browser. Idempotent — the browser dedupes a
/// repeat registration of the same script URL and scope, so calling this on
/// every mount of the phone shell is safe.
///
/// Silent no-op when there is no service worker container: the TV origin is
/// plain HTTP (D3′) and therefore not a secure context, and iOS Safari
/// without the CA installed is in the same position. The phone surface has to
/// keep working without a service worker; it only loses offline caching.
#[cfg(all(feature = "web", target_arch = "wasm32"))]
pub fn register_service_worker() {
    let Some(window) = web_sys::window() else {
        return;
    };
    let container = window.navigator().service_worker();
    // The returned promise is intentionally dropped: registration failures
    // (insecure context, user has disabled service workers) are not fatal and
    // there is nothing useful to show the user about them.
    let _ = container.register(SERVICE_WORKER_PATH);
}

/// SSR / non-wasm build: nothing to register.
#[cfg(not(all(feature = "web", target_arch = "wasm32")))]
pub fn register_service_worker() {}


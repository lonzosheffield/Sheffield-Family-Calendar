/// The three root routes' axum handlers.
///
/// They live here, next to the bytes they serve, and `server::router` only
/// wires them up — the seam `src/server/router.rs`'s own T0.6 doc comment
/// reserved for this task ("T2.2 replaces the body with the real manifest …
/// but keeps this route and its content type").
#[cfg(feature = "server")]
pub mod handlers {
    use axum::http::header;
    use axum::response::{IntoResponse, Response};

    /// `GET /manifest.webmanifest`.
    pub async fn manifest() -> impl IntoResponse {
        (
            [(header::CONTENT_TYPE, super::MANIFEST_CONTENT_TYPE)],
            super::MANIFEST_JSON,
        )
    }

    /// `GET /sw.js`.
    ///
    /// `Cache-Control: no-cache` is what lets a redeployed hub actually
    /// replace its own service worker: browsers revalidate the script on
    /// every navigation, and a cached copy would pin the old one for up to
    /// 24 hours.
    pub async fn service_worker() -> impl IntoResponse {
        (
            [
                (header::CONTENT_TYPE, super::SERVICE_WORKER_CONTENT_TYPE),
                (header::CACHE_CONTROL, "no-cache"),
                // Not one of `http`'s pre-defined constants, but the header
                // that lets a root-scoped worker be served from anywhere if
                // the path ever moves.
                (
                    header::HeaderName::from_static("service-worker-allowed"),
                    "/",
                ),
            ],
            super::SERVICE_WORKER_JS,
        )
    }

    /// `GET /icons/{file}` — the embedded PWA icon set.
    pub async fn icon(axum::extract::Path(file): axum::extract::Path<String>) -> Response {
        match super::icon_bytes(&file) {
            Some(bytes) => (
                [
                    (header::CONTENT_TYPE, "image/png"),
                    // Content is baked into the binary, so a long cache is
                    // safe: a new build is a new binary.
                    (header::CACHE_CONTROL, "public, max-age=604800"),
                ],
                bytes,
            )
                .into_response(),
            None => (axum::http::StatusCode::NOT_FOUND, "no such icon\n").into_response(),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_manifest_is_valid_json_with_a_root_scope_and_a_phone_start_url() {
        let manifest: serde_json::Value =
            serde_json::from_str(MANIFEST_JSON).expect("the manifest must be valid JSON");
        assert_eq!(manifest["scope"], "/");
        assert_eq!(manifest["start_url"], "/m");
        assert_eq!(manifest["display"], "standalone");
    }

    #[test]
    fn every_manifest_icon_resolves_to_an_embedded_file() {
        let manifest: serde_json::Value =
            serde_json::from_str(MANIFEST_JSON).expect("the manifest must be valid JSON");
        let icons = manifest["icons"].as_array().expect("icons is an array");
        assert!(icons.len() >= 2, "at least two icons are required");

        for icon in icons {
            let src = icon["src"].as_str().expect("every icon has a src");
            let name = src
                .strip_prefix("/icons/")
                .unwrap_or_else(|| panic!("{src} must be served from the root /icons/ path"));
            assert!(
                icon_bytes(name).is_some(),
                "{src} is listed in the manifest but not embedded in the binary"
            );
        }
    }

    #[test]
    fn scope_containment_matches_the_manifest_algorithm() {
        assert!(path_is_within_scope("/", "/m"));
        assert!(path_is_within_scope("/m", "/m"));
        assert!(path_is_within_scope("/m", "/m/settings"));
        assert!(!path_is_within_scope("/m/", "/mobile"));
        // The exact v1 defect (G6/R-16).
        assert!(!path_is_within_scope("/assets/", "/m"));
    }

    #[test]
    fn the_hash_heuristic_catches_asset_pipeline_urls_and_nothing_else() {
        assert!(contains_content_hash(
            "/assets/manifest-dxh1a2b3c4d5e6f708.json"
        ));
        assert!(!contains_content_hash(MANIFEST_PATH));
        assert!(!contains_content_hash(SERVICE_WORKER_PATH));
        assert!(!contains_content_hash("/icons/icon-512-maskable.png"));
    }

    #[test]
    fn the_service_worker_is_small_enough_to_ship_inline() {
        assert!(
            SERVICE_WORKER_JS.len() <= 6 * 1024,
            "sw.js is {} bytes, over the 6 KB budget",
            SERVICE_WORKER_JS.len()
        );
    }
}
